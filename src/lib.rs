//! # Biological rhythms dataset
//!
//! Measured frequencies and timings of early life, from sperm tail beat to
//! embryonic heart rate. Every value is one measurement in one species, with
//! its unit, statistic, stage, method, sample size where reported, and the
//! sources (DOI or PMID) it comes from. Each record is an R claim in
//! `claims.yaml`: referenced, not proved.
//!
//! The data (CC BY-NC 4.0) is `data/rhythms.json`, generated from
//! `data/rhythms.yaml` and embedded in the crate, so it needs no files at run
//! time. It is parsed once, on first use.
//!
//! Part of [Frequencies of Life](https://chethandvg.github.io/frequencies-of-life/).
//!
//! ```
//! use biological_rhythms_dataset::{cell_count_at, frequency_hz, get, heart_rate_at};
//!
//! let ca = get("bio:HUMAN-CA-SPIKE-INTERVAL")?;
//! assert_eq!((ca.species.as_str(), ca.min, ca.max), ("Homo sapiens", Some(10.0), Some(35.0)));
//!
//! // A spike every 10-35 minutes is 1/2100 to 1/600 Hz.
//! let hz = frequency_hz("bio:HUMAN-CA-SPIKE-INTERVAL")?;
//! assert!((hz.min - 1.0 / 2100.0).abs() < 1e-18 && (hz.max - 1.0 / 600.0).abs() < 1e-18);
//!
//! // The 7- and 8-week medians, 146 and 174 bpm, sit at the middle of their weeks.
//! assert_eq!(heart_rate_at(8.0)?, 160.0);
//! assert_eq!(cell_count_at(48.0)?, 4); // after t4 = 40.4 h, before t5 = 51.04 h
//! # Ok::<(), biological_rhythms_dataset::Error>(())
//! ```

use serde::{Deserialize, Serialize};
use std::collections::HashMap;
use std::fmt;
use std::sync::LazyLock;

/// The dataset document, exactly as generated by `scripts/build.py`.
pub const DATASET_JSON: &str = include_str!("../data/rhythms.json");

/// The series of embryonic heart-rate medians that [`heart_rate_at`] interpolates.
pub const HEART_RATE_SERIES: &str = "human-heart-rate";

/// The series of mean division times that [`cell_count_at`] steps through.
pub const CLEAVAGE_SERIES: &str = "human-cleavage";

/// What a measurement is.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum Kind {
    /// The time between repeats of a rhythm.
    Period,
    /// Repeats per second.
    Frequency,
    /// Repeats per minute.
    Rate,
    /// The length of one event.
    Duration,
    /// The time from a reference event, such as insemination.
    Time,
    /// A developmental stage, as a number of cells.
    Stage,
    /// A number of things.
    Count,
}

impl Kind {
    /// The lower-case name used in the data.
    pub fn as_str(self) -> &'static str {
        match self {
            Self::Period => "period",
            Self::Frequency => "frequency",
            Self::Rate => "rate",
            Self::Duration => "duration",
            Self::Time => "time",
            Self::Stage => "stage",
            Self::Count => "count",
        }
    }
}

/// The unit of a measurement.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum Unit {
    /// Hertz.
    #[serde(rename = "Hz")]
    Hz,
    /// Seconds.
    #[serde(rename = "s")]
    Seconds,
    /// Minutes.
    #[serde(rename = "min")]
    Minutes,
    /// Hours.
    #[serde(rename = "h")]
    Hours,
    /// Beats per minute.
    #[serde(rename = "bpm")]
    Bpm,
    /// Events per minute.
    #[serde(rename = "/min")]
    PerMinute,
    /// Cells.
    #[serde(rename = "cells")]
    Cells,
    /// Zinc sparks.
    #[serde(rename = "sparks")]
    Sparks,
    /// Vesicles.
    #[serde(rename = "vesicles")]
    Vesicles,
    /// Atoms.
    #[serde(rename = "atoms")]
    Atoms,
}

/// A reference that a measurement comes from.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Source {
    /// The key in `data/sources.yaml`.
    pub key: String,
    /// Short citation: authors, year, journal, volume and pages.
    pub cite: String,
    /// The article title.
    pub title: String,
    /// The DOI, if the article has one.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub doi: Option<String>,
    /// The PubMed ID, if the article has one.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub pmid: Option<String>,
}

/// One measurement: one quantity in one species, with its method and sources.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Rhythm {
    /// The claim id, such as `bio:HUMAN-CA-SPIKE-INTERVAL`. Permanent.
    pub id: String,
    /// The claim version; the major version changes when the meaning does.
    pub version: String,
    /// The topic, such as `egg-activation` or `heart`.
    pub topic: String,
    /// What was measured, in plain words that name the species.
    pub quantity: String,
    /// The species, as a binomial name (`Homo sapiens` or `Mus musculus`).
    pub species: String,
    /// What kind of quantity this is.
    pub kind: Kind,
    /// The value, when a single value is reported.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub value: Option<f64>,
    /// The lower end, when a range is reported.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub min: Option<f64>,
    /// The upper end, when a range is reported.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub max: Option<f64>,
    /// The unit of `value`, `min` and `max`.
    pub unit: Unit,
    /// What the number is: `mean`, `median`, `range`, `approximate`, `estimate`, `observed` or `reported`.
    pub statistic: String,
    /// The developmental stage or condition measured.
    pub stage: String,
    /// How it was measured.
    pub method: String,
    /// The sample size, when reported.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub n: Option<u32>,
    /// What `n` counts.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub n_unit: Option<String>,
    /// The series a helper function reads this record from, if any.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub series: Option<String>,
    /// The record's position in its series (a gestational week, or a number of cells).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub at: Option<f64>,
    /// Further detail from the sources.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub notes: Option<String>,
    /// Why the value is disputed or has been revised, when it is.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub contested: Option<String>,
    /// The references; the first is the source of the value.
    pub sources: Vec<Source>,
}

impl Rhythm {
    /// The record as one line of JSON, with the same fields as in `data/rhythms.json`.
    pub fn to_json(&self) -> String {
        serde_json::to_string(self).expect("a record always serialises")
    }
}

/// A frequency range in hertz; `min == max` for a single value.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct HzRange {
    /// The lowest frequency.
    pub min: f64,
    /// The highest frequency.
    pub max: f64,
}

/// Why a lookup or helper failed.
#[derive(Debug, Clone, PartialEq)]
#[non_exhaustive]
pub enum Error {
    /// No record has this id.
    UnknownId(String),
    /// The record is not a period, frequency or rate, so it has no frequency.
    NotARhythm {
        /// The record's id.
        id: String,
        /// What the record is instead.
        kind: Kind,
    },
    /// An argument is outside the range the data covers, or is not a finite number.
    OutOfRange {
        /// The argument's name.
        name: &'static str,
        /// The value given.
        value: f64,
        /// The smallest value covered.
        min: f64,
        /// The largest value covered.
        max: f64,
    },
    /// A unit conversion in `rhythm-units` rejected a value.
    Units(rhythm_units::RhythmError),
}

impl fmt::Display for Error {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::UnknownId(id) => write!(f, "no record has the id {id:?}"),
            Self::NotARhythm { id, kind } => write!(
                f,
                "{id} is a {}, not a period, frequency or rate",
                kind.as_str()
            ),
            Self::OutOfRange {
                name,
                value,
                min,
                max,
            } => write!(
                f,
                "{name} must be a number from {min} to {max}, the range the data covers; got {value}"
            ),
            Self::Units(e) => e.fmt(f),
        }
    }
}

impl std::error::Error for Error {}

impl From<rhythm_units::RhythmError> for Error {
    fn from(e: rhythm_units::RhythmError) -> Self {
        Self::Units(e)
    }
}

/// The result type of this crate.
pub type Result<T> = std::result::Result<T, Error>;

#[derive(Deserialize)]
struct Document {
    series: HashMap<String, SeriesInfo>,
    rhythms: Vec<Rhythm>,
}

/// How a helper reads a series: each record sits at its `at` plus `offset`.
#[derive(Deserialize)]
struct SeriesInfo {
    #[serde(default)]
    offset: f64,
}

/// The parsed dataset and the indexes the helpers use.
struct Dataset {
    rhythms: Vec<Rhythm>,
    by_id: HashMap<String, usize>,
    /// (gestational week the median is placed at, median bpm), by week.
    heart_rate: Vec<(f64, f64)>,
    /// (mean hours after insemination, cells), by time.
    cleavage: Vec<(f64, u32)>,
}

static DATA: LazyLock<Dataset> = LazyLock::new(|| {
    let doc: Document = serde_json::from_str(DATASET_JSON).expect("data/rhythms.json is valid");
    let series = |name: &str| {
        let offset = doc
            .series
            .get(name)
            .expect("data/rhythms.json describes every series")
            .offset;
        let mut points: Vec<(f64, f64)> = doc
            .rhythms
            .iter()
            .filter(|r| r.series.as_deref() == Some(name))
            .map(|r| {
                (
                    r.at.expect("series records have `at`") + offset,
                    r.value.expect("series records have a value"),
                )
            })
            .collect();
        points.sort_by(|a, b| a.0.total_cmp(&b.0));
        assert!(
            points.len() >= 2,
            "series {name} needs at least two records"
        );
        points
    };
    let heart_rate = series(HEART_RATE_SERIES);
    let mut cleavage: Vec<(f64, u32)> = series(CLEAVAGE_SERIES)
        .into_iter()
        .map(|(cells, hours)| (hours, cells as u32))
        .collect();
    cleavage.sort_by(|a, b| a.0.total_cmp(&b.0));
    let by_id = doc
        .rhythms
        .iter()
        .enumerate()
        .map(|(i, r)| (r.id.clone(), i))
        .collect();
    Dataset {
        rhythms: doc.rhythms,
        by_id,
        heart_rate,
        cleavage,
    }
});

/// Every record, in the order of `data/rhythms.yaml`.
pub fn rhythms() -> &'static [Rhythm] {
    &DATA.rhythms
}

/// Every record as a JSON array, with the same fields as in `data/rhythms.json`.
pub fn rhythms_json() -> String {
    serde_json::to_string(rhythms()).expect("records always serialise")
}

/// The record with this claim id.
pub fn get(id: &str) -> Result<&'static Rhythm> {
    DATA.by_id
        .get(id)
        .map(|&i| &DATA.rhythms[i])
        .ok_or_else(|| Error::UnknownId(id.to_owned()))
}

/// The frequency of a period, frequency or rate, in hertz, using `rhythm-units`.
///
/// A period `T` becomes `1 / T` and a rate of `b` per minute becomes `b / 60`.
/// A range of periods gives the range of frequencies, with the longest period
/// as the lowest frequency. Durations, time points, stages and counts are not
/// rhythms and give [`Error::NotARhythm`].
pub fn frequency_hz(id: &str) -> Result<HzRange> {
    let r = get(id)?;
    let hz = |x: f64| -> Result<f64> {
        Ok(match (r.kind, r.unit) {
            // Already in hertz: speeding time up by 1 is the identity, with the same positivity check.
            (Kind::Frequency, Unit::Hz) => rhythm_units::scale_frequency(x, 1.0)?,
            (Kind::Period, Unit::Seconds) => rhythm_units::hz_from_period(x)?,
            (Kind::Period, Unit::Minutes) => rhythm_units::hz_from_period_minutes(x)?,
            (Kind::Period, Unit::Hours) => rhythm_units::hz_from_period_minutes(60.0 * x)?,
            (Kind::Rate, Unit::Bpm | Unit::PerMinute) => rhythm_units::hz_from_bpm(x)?,
            (kind, _) => {
                return Err(Error::NotARhythm {
                    id: r.id.clone(),
                    kind,
                });
            }
        })
    };
    let (a, b) = match (r.value, r.min, r.max) {
        (Some(v), _, _) => (hz(v)?, hz(v)?),
        (None, Some(lo), Some(hi)) => (hz(lo)?, hz(hi)?),
        _ => unreachable!("data/rhythms.json is validated to have a value or a range"),
    };
    Ok(HzRange {
        min: a.min(b),
        max: a.max(b),
    })
}

/// Linear interpolation through `(w0, b0)` and `(w1, b1)` at `x`, as `lerp` in
/// `proofs/BiologicalRhythmsDataset/Interpolation.lean`. The result is clamped to
/// the range of `b0` and `b1`, which the Lean proof shows changes nothing in exact
/// arithmetic, so that floating-point rounding cannot leave that range either.
fn lerp((w0, b0): (f64, f64), (w1, b1): (f64, f64), x: f64) -> f64 {
    (b0 + (x - w0) * (b1 - b0) / (w1 - w0)).clamp(b0.min(b1), b0.max(b1))
}

/// Rejects `value` unless it is a number in `[min, max]` (so NaN is rejected too).
fn within(name: &'static str, value: f64, min: f64, max: f64) -> Result<f64> {
    if (min..=max).contains(&value) {
        Ok(value)
    } else {
        Err(Error::OutOfRange {
            name,
            value,
            min,
            max,
        })
    }
}

/// Median human embryonic heart rate (bpm) at `weeks` of gestation.
///
/// Ouyang et al. 2020 give one median for each gestational week from 6 to 10.
/// Each is placed at the middle of its week (the week-6 median at 6.5 weeks, and
/// so on: the model assumption `bio:HEART-RATE-WEEK-PLACEMENT`), returned exactly
/// there, and interpolated linearly in between. Weeks before the first median or
/// after the last, outside 6.5 to 10.5, give [`Error::OutOfRange`].
pub fn heart_rate_at(weeks: f64) -> Result<f64> {
    let points = &DATA.heart_rate;
    let (first, last) = (points[0].0, points[points.len() - 1].0);
    let x = within("weeks", weeks, first, last)?;
    let i = points.partition_point(|&(w, _)| w < x);
    if points[i].0 == x {
        return Ok(points[i].1);
    }
    Ok(lerp(points[i - 1], points[i], x))
}

/// Number of cells in a human embryo `hours` after insemination, as a step
/// function over the mean division times t2 to t8 (Lorenzo Rodríguez et al. 2026).
///
/// Returns 1 before t2 and `k` from tk until the next division. These are times
/// of the mean embryo; single embryos vary by hours. After t8 the dataset has
/// no division times, so hours after t8, and negative hours, give
/// [`Error::OutOfRange`].
pub fn cell_count_at(hours: f64) -> Result<u32> {
    let steps = &DATA.cleavage;
    let x = within("hours", hours, 0.0, steps[steps.len() - 1].0)?;
    let i = steps.partition_point(|&(t, _)| t <= x);
    Ok(if i == 0 { 1 } else { steps[i - 1].1 })
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Reads every number as f64, so that 10 and 10.0 compare equal.
    fn numbers_as_f64(v: serde_json::Value) -> serde_json::Value {
        use serde_json::Value;
        match v {
            Value::Number(n) => n.as_f64().into(),
            Value::Array(items) => items.into_iter().map(numbers_as_f64).collect(),
            Value::Object(map) => Value::Object(
                map.into_iter()
                    .map(|(k, v)| (k, numbers_as_f64(v)))
                    .collect(),
            ),
            other => other,
        }
    }

    #[test]
    fn every_record_round_trips_unchanged() {
        let doc: serde_json::Value = serde_json::from_str(DATASET_JSON).unwrap();
        let ours: serde_json::Value = serde_json::from_str(&rhythms_json()).unwrap();
        assert_eq!(numbers_as_f64(ours), numbers_as_f64(doc["rhythms"].clone()));
        for r in rhythms() {
            assert_eq!(get(&r.id).unwrap(), r);
        }
    }

    #[test]
    fn heart_rate_is_exact_at_each_measured_week() {
        for &(w, bpm) in &DATA.heart_rate {
            assert_eq!(heart_rate_at(w).unwrap(), bpm);
        }
        assert_eq!(
            DATA.heart_rate[0],
            (6.5, 117.0),
            "each median sits at mid-week"
        );
        assert_eq!(heart_rate_at(9.0).unwrap(), 175.0);
    }

    #[test]
    fn heart_rate_stays_between_the_bracketing_medians() {
        for pair in DATA.heart_rate.windows(2) {
            let ((w0, b0), (w1, b1)) = (pair[0], pair[1]);
            for k in 0..=1000 {
                let x = w0 + (w1 - w0) * f64::from(k) / 1000.0;
                let y = heart_rate_at(x).unwrap();
                assert!(b0.min(b1) <= y && y <= b0.max(b1), "{x} -> {y}");
            }
        }
    }

    #[test]
    fn helpers_reject_values_outside_the_data() {
        for bad in [
            6.0,
            6.499,
            10.501,
            f64::NAN,
            f64::INFINITY,
            f64::NEG_INFINITY,
        ] {
            assert!(heart_rate_at(bad).is_err(), "{bad}");
        }
        for bad in [-0.001, 61.52, f64::NAN, f64::INFINITY] {
            assert!(cell_count_at(bad).is_err(), "{bad}");
        }
        assert_eq!(
            heart_rate_at(11.0).unwrap_err().to_string(),
            "weeks must be a number from 6.5 to 10.5, the range the data covers; got 11"
        );
    }

    #[test]
    fn cell_count_steps_up_at_each_division() {
        assert_eq!(cell_count_at(0.0).unwrap(), 1);
        let mut previous = 1;
        for &(t, cells) in &DATA.cleavage {
            assert_eq!(cell_count_at(t).unwrap(), cells);
            assert_eq!(cell_count_at(t - 1e-9).unwrap(), previous);
            previous = cells;
        }
        assert_eq!(previous, 8);
    }

    #[test]
    fn only_rhythms_have_a_frequency() {
        let err = frequency_hz("bio:HUMAN-CA-SPIKE-DURATION").unwrap_err();
        assert_eq!(
            err.to_string(),
            "bio:HUMAN-CA-SPIKE-DURATION is a duration, not a period, frequency or rate"
        );
        assert_eq!(
            frequency_hz("bio:NOPE").unwrap_err(),
            Error::UnknownId("bio:NOPE".into())
        );
        let beat = frequency_hz("bio:HUMAN-SPERM-BEAT-VISCOUS").unwrap();
        assert_eq!((beat.min, beat.max), (10.0, 10.0));
    }

    #[test]
    fn species_are_never_mixed() {
        for r in rhythms() {
            let prefix = match r.species.as_str() {
                "Homo sapiens" => "bio:HUMAN-",
                "Mus musculus" => "bio:MOUSE-",
                other => panic!("{}: unexpected species {other}", r.id),
            };
            assert!(r.id.starts_with(prefix), "{}", r.id);
            assert!(!r.sources.is_empty(), "{}", r.id);
        }
    }
}
